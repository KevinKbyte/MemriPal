"""Generate the offline demo fixtures (MEM-005). Deterministic and idempotent.

Usage: uv run python scripts/make_synthetic_fixtures.py
Writes fixtures/demo/photo.jpg, replayable responses under fixtures/replay/, and fixtures/MANIFEST.md.
"""

import hashlib
import io
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw

from memripal.backend import CacheKey, ResponseCache

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"
SOURCE = "synthetic, generated by scripts/make_synthetic_fixtures.py"
LICENSE = "MIT (own work)"

# Bounding boxes (x0, y0, x1, y1) of the drawn objects; reused as the fake segmentation output.
OBJECTS = {
    "book": (180, 250, 240, 420),
    "mug": (480, 350, 560, 420),
    "lamp": (760, 140, 880, 420),
}


def draw_shelf() -> Image.Image:
    img = Image.new("RGB", (1024, 768), (226, 218, 200))
    draw = ImageDraw.Draw(img)
    for y in (420, 640):
        draw.rectangle((80, y, 944, y + 24), fill=(120, 80, 45))
    draw.rectangle(OBJECTS["book"], fill=(40, 70, 150))
    draw.rectangle((250, 270, 300, 420), fill=(150, 40, 40))
    draw.rectangle((310, 290, 350, 420), fill=(40, 130, 70))
    draw.rectangle(OBJECTS["mug"], fill=(240, 240, 235), outline=(60, 60, 60), width=3)
    draw.arc((545, 365, 590, 405), 270, 90, fill=(60, 60, 60), width=6)
    lx0, ly0, lx1, ly1 = OBJECTS["lamp"]
    draw.polygon([(lx0, ly0 + 100), (lx1, ly0 + 100), (lx1 - 30, ly0), (lx0 + 30, ly0)], fill=(245, 205, 90))
    draw.rectangle((815, ly0 + 100, 825, ly1 - 15), fill=(70, 70, 70))
    draw.rectangle((780, ly1 - 15, 860, ly1), fill=(70, 70, 70))
    return img


def to_bytes(img: Image.Image, fmt: str, **kwargs) -> bytes:
    buf = io.BytesIO()
    img.save(buf, format=fmt, **kwargs)
    return buf.getvalue()


def main() -> int:
    shelf = draw_shelf()
    photo_bytes = to_bytes(shelf, "JPEG", quality=90)
    photo = FIXTURES / "demo" / "photo.jpg"
    photo.parent.mkdir(parents=True, exist_ok=True)
    photo.write_bytes(photo_bytes)
    photo_sha = hashlib.sha256(photo_bytes).hexdigest()

    cache = ResponseCache(FIXTURES / "replay")
    written = [photo]
    for phrase, (x0, y0, x1, y1) in OBJECTS.items():
        text = f"<ref>{phrase}</ref><box>({x0},{y0}),({x1},{y1})</box>\n"
        written.append(cache.put(CacheKey("segment", photo_sha, phrase), text.encode("utf-8")))
    phrases = json.dumps({"phrases": list(OBJECTS)}, indent=2) + "\n"
    written.append(cache.put(CacheKey("spark_json", photo_sha, "phrases"), phrases.encode("utf-8")))
    edit = shelf.crop(OBJECTS["book"]).resize((120, 340))
    edit_webp = to_bytes(edit, "WEBP", lossless=True)
    written.append(cache.put(CacheKey("image_edit", photo_sha, "book"), edit_webp))

    header = ["# Fixtures manifest", "", "| Path | Source | License |", "| --- | --- | --- |"]
    rows = [f"| `{p.relative_to(FIXTURES).as_posix()}` | {SOURCE} | {LICENSE} |" for p in sorted(written)]
    manifest = "\n".join([*header, *rows])
    (FIXTURES / "MANIFEST.md").write_text(manifest + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(written)} fixtures + MANIFEST.md under {FIXTURES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
