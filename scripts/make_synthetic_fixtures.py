"""Generate the offline demo fixtures (MEM-005, MEM-017). Deterministic and idempotent.

Usage: uv run python scripts/make_synthetic_fixtures.py
Writes fixtures/demo/photo.jpg, replayable responses under fixtures/replay/, and fixtures/MANIFEST.md.
"""

import hashlib
import io
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw

from memripal.backend import CacheKey, ModelRequest, ResponseCache
from memripal.imaging import process_upload
from memripal.loci import SAM_MODEL, SPARK_GEN_PARAMS, SPARK_MODEL
from memripal.probe import PHRASE_SCHEMA

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"
SOURCE = "synthetic, generated by scripts/make_synthetic_fixtures.py"
LICENSE = "MIT (own work)"

# Bounding boxes (x0, y0, x1, y1) of the drawn objects; reused as the legacy MEM-005 segmentation output.
OBJECTS = {
    "book": (180, 250, 240, 420),
    "mug": (480, 350, 560, 420),
    "lamp": (760, 140, 880, 420),
}

# MEM-017 scene: one box per Spark phrase, each 0.5%-40% of the frame, non-overlapping and with centroids
# more than 5% of the diagonal apart, so select_loci keeps all 12 in the first round (no re-ask fixture).
SCENE = {
    "blue book": OBJECTS["book"],
    "red book": (260, 270, 310, 420),
    "green book": (330, 290, 380, 420),
    "white mug": OBJECTS["mug"],
    "desk lamp": OBJECTS["lamp"],
    "wall clock": (560, 60, 660, 160),
    "picture frame": (120, 40, 320, 180),
    "potted plant": (620, 280, 720, 420),
    "storage box": (120, 520, 300, 640),
    "radio": (360, 560, 500, 640),
    "vase": (560, 500, 620, 640),
    "teddy bear": (700, 530, 800, 640),
}

DARK = (60, 60, 60)


def draw_shelf() -> Image.Image:
    img = Image.new("RGB", (1024, 768), (226, 218, 200))
    draw = ImageDraw.Draw(img)
    for y in (420, 640):
        draw.rectangle((80, y, 944, y + 24), fill=(120, 80, 45))
    draw.rectangle(SCENE["blue book"], fill=(40, 70, 150))
    draw.rectangle(SCENE["red book"], fill=(150, 40, 40))
    draw.rectangle(SCENE["green book"], fill=(40, 130, 70))
    draw.rectangle(SCENE["white mug"], fill=(240, 240, 235), outline=DARK, width=3)
    draw.arc((545, 365, 590, 405), 270, 90, fill=DARK, width=6)
    lx0, ly0, lx1, ly1 = SCENE["desk lamp"]
    draw.polygon([(lx0, ly0 + 100), (lx1, ly0 + 100), (lx1 - 30, ly0), (lx0 + 30, ly0)], fill=(245, 205, 90))
    draw.rectangle((815, ly0 + 100, 825, ly1 - 15), fill=(70, 70, 70))
    draw.rectangle((780, ly1 - 15, 860, ly1), fill=(70, 70, 70))
    draw.ellipse(SCENE["wall clock"], fill=(250, 250, 245), outline=DARK, width=5)
    draw.line((610, 110, 610, 75), fill=DARK, width=4)
    draw.line((610, 110, 640, 110), fill=DARK, width=4)
    draw.rectangle(SCENE["picture frame"], fill=(150, 200, 230), outline=(110, 70, 30), width=10)
    draw.polygon([(130, 170), (200, 100), (260, 140), (310, 110), (310, 170)], fill=(70, 150, 80))
    draw.polygon([(640, 360), (700, 360), (690, 420), (650, 420)], fill=(180, 90, 50))
    for leaf in ((620, 300, 670, 365), (670, 300, 720, 365), (645, 280, 695, 340)):
        draw.ellipse(leaf, fill=(50, 140, 60))
    draw.rectangle(SCENE["storage box"], fill=(200, 160, 110), outline=(120, 90, 50), width=4)
    draw.rectangle((180, 560, 240, 590), fill=(245, 240, 225))
    draw.rectangle(SCENE["radio"], fill=(90, 60, 50), outline=DARK, width=3)
    draw.ellipse((375, 575, 425, 625), fill=(40, 40, 40))
    draw.rectangle((440, 580, 485, 600), fill=(230, 220, 160))
    vase = [(575, 500), (605, 500), (620, 580), (600, 640), (580, 640), (560, 580)]
    draw.polygon(vase, fill=(60, 110, 190))
    draw.ellipse((715, 580, 785, 640), fill=(150, 100, 60))
    draw.ellipse((725, 535, 775, 585), fill=(150, 100, 60))
    draw.ellipse((715, 530, 735, 550), fill=(130, 85, 50))
    draw.ellipse((765, 530, 785, 550), fill=(130, 85, 50))
    return img


def to_bytes(img: Image.Image, fmt: str, **kwargs) -> bytes:
    buf = io.BytesIO()
    img.save(buf, format=fmt, **kwargs)
    return buf.getvalue()


def loci_entries(cache: ResponseCache, photo_bytes: bytes) -> list[Path]:
    """Replays keyed by exactly the requests find_loci derives from process_upload(photo) (MEM-017)."""
    processed = process_upload(photo_bytes)
    spark = ModelRequest(
        method="spark_json",
        image_jpeg=processed.jpeg,
        subject="phrases",
        attempt=0,
        model=SPARK_MODEL,
        prompt_template_id="phrase",
        gen_params=dict(SPARK_GEN_PARAMS),
        schema=PHRASE_SCHEMA,
    )
    phrases = json.dumps({"phrases": list(SCENE)}, indent=2) + "\n"
    written = [cache.put(spark.cache_key(), phrases.encode("utf-8"))]
    w, h = processed.width, processed.height
    for phrase, (x0, y0, x1, y1) in SCENE.items():
        seg = ModelRequest(
            method="segment",
            image_jpeg=processed.jpeg,
            subject=phrase,
            attempt=0,
            model=SAM_MODEL,
            prompt_template_id="sam-phrase",
            gen_params={},
            schema=None,
        )
        text = f"<|box;x1={x0};y1={y0};x2={x1};y2={y1};w={w};h={h}|>\n"
        written.append(cache.put(seg.cache_key(), text.encode("utf-8")))
    return written


def main() -> int:
    shelf = draw_shelf()
    photo_bytes = to_bytes(shelf, "JPEG", quality=90)
    photo = FIXTURES / "demo" / "photo.jpg"
    photo.parent.mkdir(parents=True, exist_ok=True)
    photo.write_bytes(photo_bytes)
    photo_sha = hashlib.sha256(photo_bytes).hexdigest()

    cache = ResponseCache(FIXTURES / "replay")
    written = [photo]
    for phrase, (x0, y0, x1, y1) in OBJECTS.items():
        text = f"<ref>{phrase}</ref><box>({x0},{y0}),({x1},{y1})</box>\n"
        written.append(cache.put(CacheKey("segment", photo_sha, phrase), text.encode("utf-8")))
    phrases = json.dumps({"phrases": list(OBJECTS)}, indent=2) + "\n"
    written.append(cache.put(CacheKey("spark_json", photo_sha, "phrases"), phrases.encode("utf-8")))
    edit = shelf.crop(OBJECTS["book"]).resize((120, 340))
    edit_webp = to_bytes(edit, "WEBP", lossless=True)
    written.append(cache.put(CacheKey("image_edit", photo_sha, "book"), edit_webp))
    written.extend(loci_entries(cache, photo_bytes))

    header = ["# Fixtures manifest", "", "| Path | Source | License |", "| --- | --- | --- |"]
    rows = [f"| `{p.relative_to(FIXTURES).as_posix()}` | {SOURCE} | {LICENSE} |" for p in sorted(written)]
    manifest = "\n".join([*header, *rows])
    (FIXTURES / "MANIFEST.md").write_text(manifest + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(written)} fixtures + MANIFEST.md under {FIXTURES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
