def to_bytes(img: Image.Image, fmt: str, **kwargs) -> bytes:
    buf = io.BytesIO()
    img.save(buf, format=fmt, **kwargs)
    return buf.getvalue()


def loci_entries(cache: ResponseCache, photo_bytes: bytes) -> list[Path]:
    """Replays keyed by exactly the requests find_loci derives from process_upload(photo) (MEM-017)."""
    processed = process_upload(photo_bytes)
    spark = ModelRequest(
        method="spark_json",
        image_jpeg=processed.jpeg,
        subject="phrases",
        attempt=0,
        model=SPARK_MODEL,
        prompt_template_id="phrase",
        gen_params=dict(SPARK_GEN_PARAMS),
        schema=PHRASE_SCHEMA,
    )
    phrases = json.dumps({"phrases": list(SCENE)}, indent=2) + "\n"
    written = [cache.put(spark.cache_key(), phrases.encode("utf-8"))]
    w, h = processed.width, processed.height
    for phrase, (x0, y0, x1, y1) in SCENE.items():
        seg = ModelRequest(
            method="segment",
            image_jpeg=processed.jpeg,
            subject=phrase,
            attempt=0,
            model=SAM_MODEL,
            prompt_template_id="sam-phrase",
            gen_params={},
            schema=None,
        )
        text = f"<|box;x1={x0};y1={y0};x2={x1};y2={y1};w={w};h={h}|>\n"
        written.append(cache.put(seg.cache_key(), text.encode("utf-8")))
    return written


class ReplyRecorder:
    """Answers every request with one canned reply, recorded under that request's own cache key.

    Running the real split_notes/associate against it keys each replay exactly as replay will look it up.
    """

    mode = "fixture"

    def __init__(self, cache: ResponseCache, reply: dict, written: list[Path]) -> None:
        self.cache, self.reply, self.written = cache, reply, written

    def call(self, req: ModelRequest) -> dict:
        body = json.dumps(self.reply, indent=2) + "\n"
        self.written.append(self.cache.put(req.cache_key(), body.encode("utf-8")))
        return self.reply


class BytesRecorder:
    """Answers one request with canned image bytes, recorded under that request's own cache key."""

    mode = "fixture"

    def __init__(self, cache: ResponseCache, reply: bytes, written: list[Path]) -> None:
        self.cache, self.reply, self.written = cache, reply, written

    def call(self, req: ModelRequest) -> bytes:
        self.written.append(self.cache.put(req.cache_key(), self.reply))
        return self.reply


def scene_edit(shelf: Image.Image, box: tuple[int, int, int, int], size: tuple[int, int]) -> bytes:
    """A small tier-1 demo scene: the shelf with a gold banner on the locus (render_scene resizes it).

    `box` is in processed-image coordinates, so it scales by the processed `size`, not the shelf's.
    """
    w, h = 256, 192
    sx, sy = w / size[0], h / size[1]
    img = shelf.resize((w, h))
    x0, y0, x1, y1 = box
    ImageDraw.Draw(img).rectangle(
        (round(x0 * sx), round(y0 * sy), round(x1 * sx), round(y1 * sy)), outline=(212, 160, 23), width=3
    )
    return to_bytes(img, "WEBP", lossless=True)


def association_record(n: int, item: str, locus: str, quote: str) -> dict:
    return {
        "item": item,
        "locus": locus,
        "kinesthetic": f"You lift the {locus} and feel it grow heavy with the idea: {item}.",
        "auditory": f"The {locus} speaks in a booming voice: {item}!",
        "visual": f"A glowing gold banner is wrapped around the {locus}, painted with bright letters.",
        "emotional": f"A jolt of surprise and delight hits you as the {locus} comes alive.",
        "conceptual": f"The {locus} is the anchor for the point: {item}.",
        "olfactory": f"A sharp smell of fresh ink drifts up from the {locus}.",
        "gustatory": f"A sweet taste of honey fills your mouth as you touch the {locus}.",
        "spatial": f"The {locus} is stop {n} on your walk along the shelf.",
        "scene_prompt_details": f"The {locus} on a wooden shelf, wrapped in a glowing gold banner.",
        "walk_cue": f"Stop {n}: look at the {locus}.",
        "reencode_hint": f"Say the point aloud while you picture the banner on the {locus}.",
        "question": f"Why does this point matter: {item}?",
        "answer": f"As the talk puts it: {quote}",
    }


def notes_entries(
    cache: ResponseCache, processed: Processed, places: list[dict], shelf: Image.Image
) -> list[Path]:
    """The demo notes plus the split and association replays the offline associate flow needs (MEM-023).

    Each pair is also recorded once per demo place, since a confirmed place is part of the request key
    (MEM-025): any chip the user confirms in the demo still replays. The first pair (no place) also gets
    one tier-1 scene replay, so the demo shows a real scene and its overlay (MEM-044).
    """
    notes = FIXTURES / "demo" / "notes.txt"
    notes.write_bytes(NOTES.encode("utf-8"))
    written = [notes]
    # A frozen clock keeps the deadline out of play, as in replay.
    found = find_loci(FixtureBackend(cache.root), processed, clock=lambda: 0.0).loci
    loci = [lc.label for lc in found]
    reply = {"points": [{"label": label, "source_quote": quote} for label, quote in POINTS]}
    points = split_notes(ReplyRecorder(cache, reply, written), processed.jpeg, NOTES, len(loci))
    for n, (point, locus) in enumerate(zip(points, loci, strict=True), start=1):
        record = association_record(n, point["label"], locus, point["source_quote"])
        result = associate(ReplyRecorder(cache, record, written), processed, point["label"], locus)
        if n == 1:
            b = found[0].box
            box = {"x1": b.x1, "y1": b.y1, "x2": b.x2, "y2": b.y2}
            edit = scene_edit(shelf, (b.x1, b.y1, b.x2, b.y2), (processed.width, processed.height))
            render_scene(BytesRecorder(cache, edit, written), processed, box, result.record)
        for hit in places:
            place = {"title": hit["title"], "extract": hit["extract"]}
            spatial = f"The {locus} is stop {n} on your walk, set here at {hit['title']}."
            placed = {**record, "spatial": spatial}
            associate(ReplyRecorder(cache, placed, written), processed, point["label"], locus, place)
    return written


def _wikipedia_replay(request: httpx.Request) -> httpx.Response:
    """Answers PlaceProvider's GeoSearch and summary requests from the recorded PLACE_HITS/PLACE_EXTRACTS."""
    url = str(request.url)
    if url.startswith(SUMMARY_URL):
        title = unquote(url[len(SUMMARY_URL) :]).replace("_", " ")
        return httpx.Response(200, json={"title": title, "extract": PLACE_EXTRACTS[title]})
    hits = [{"title": title, "dist": dist} for title, dist in PLACE_HITS]
    return httpx.Response(200, json={"batchcomplete": "", "query": {"geosearch": hits}})


def place_entries(cache: ResponseCache) -> tuple[list[Path], list[dict]]:
    """The demo place sidecar plus the /place replay, made by the real PlaceProvider (MEM-025)."""
    sidecar = FIXTURES / "demo" / "place.json"
    sidecar.write_bytes((json.dumps(DEMO_PLACE) + "\n").encode("ascii"))
    lat, lon = DEMO_PLACE["lat"], DEMO_PLACE["lon"]
    places = PlaceProvider(transport=httpx.MockTransport(_wikipedia_replay)).lookup(lat, lon)
    replay = replay_path(cache.root, lat, lon)
    replay.parent.mkdir(parents=True, exist_ok=True)
    replay.write_bytes((json.dumps({"places": places}, indent=2) + "\n").encode("ascii"))
    return [sidecar, replay], places


def foreign_rows(manifest: Path) -> list[str]:
    """Existing MANIFEST rows whose Source this script does not own, verbatim and in order (MEM-043 M1).

    They follow the generated rows, where gen_room_fixtures.py and promote_live_cache.py append theirs,
    so a regeneration with rooms or promoted replays committed leaves MANIFEST.md byte-identical.
    """
    if not manifest.is_file():
        return []
    kept = []
    for line in manifest.read_text(encoding="utf-8").splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) == 3 and cells[0].startswith("`") and cells[1] not in (SOURCE, PLACE_SOURCE):
            kept.append(line)
    return kept


def main() -> int:
    shelf = draw_shelf()
    photo_bytes = to_bytes(shelf, "JPEG", quality=90)
    photo = FIXTURES / "demo" / "photo.jpg"
    photo.parent.mkdir(parents=True, exist_ok=True)
    photo.write_bytes(photo_bytes)
    photo_sha = hashlib.sha256(photo_bytes).hexdigest()

    cache = ResponseCache(FIXTURES / "replay")
    written = [photo]
    for phrase, (x0, y0, x1, y1) in OBJECTS.items():
        text = f"<ref>{phrase}</ref><box>({x0},{y0}),({x1},{y1})</box>\n"
        written.append(cache.put(CacheKey("segment", photo_sha, phrase), text.encode("utf-8")))
    phrases = json.dumps({"phrases": list(OBJECTS)}, indent=2) + "\n"
    written.append(cache.put(CacheKey("spark_json", photo_sha, "phrases"), phrases.encode("utf-8")))
    edit = shelf.crop(OBJECTS["book"]).resize((120, 340))
    edit_webp = to_bytes(edit, "WEBP", lossless=True)
    written.append(cache.put(CacheKey("image_edit", photo_sha, "book"), edit_webp))
    written.extend(loci_entries(cache, photo_bytes))
    place_files, places = place_entries(cache)
    written.extend(place_files)
    written.extend(notes_entries(cache, process_upload(photo_bytes), places, shelf))
    recall = FIXTURES / "demo" / "recall_timeline.json"
    recall.write_bytes((json.dumps(RECALL_TIMELINE, indent=2) + "\n").encode("ascii"))
    written.append(recall)

    # Wikipedia text is CC BY-SA, so its replay is credited apart from the synthetic files.
    credits = {place_files[1]: (PLACE_SOURCE, PLACE_LICENSE)}
    header = ["# Fixtures manifest", "", "| Path | Source | License |", "| --- | --- | --- |"]
    rows = [
        f"| `{p.relative_to(FIXTURES).as_posix()}` | {' | '.join(credits.get(p, (SOURCE, LICENSE)))} |"
        for p in sorted(written)
    ]
    manifest_path = FIXTURES / "MANIFEST.md"
    manifest = "\n".join([*header, *rows, *foreign_rows(manifest_path)])
    manifest_path.write_text(manifest + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(written)} fixtures + MANIFEST.md under {FIXTURES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
