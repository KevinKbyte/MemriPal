# Covers: MEM-043
# Requirement (P1, M1): `python scripts/promote_live_cache.py --room <room_id> [--dry-run]` runs offline
# with no key and copies from refs/private/live-cache/<method>/ into fixtures/replay/<method>/ only the
# entries recorded for that room's processed photo (process_upload(fixtures/rooms/<room_id>.webp)):
# never photos/, never another photo's entry (private live runs share that cache, ADR 0017), and never
# an entry it cannot attribute to the room. Each copied file gets a fixtures/MANIFEST.md row (Source
# "live Meta responses for room <room_id>, promoted by scripts/promote_live_cache.py, <YYYY-MM-DD>",
# License citing ADR 0029) and existing rows are kept. A target with equal bytes is skipped (a re-run
# changes nothing, not even an mtime); a target with different bytes -> stderr, exit 1, nothing
# written. --dry-run prints the target paths and writes nothing. Copied files pass precommit_scan.py.
#
# Decision (Q23 default): a cache entry ties to a room through the backend, by the room photo's bytes:
# the entries are the ones the real MetaBackend wrote for process_upload(room photo), as seeded here by
# running find_loci; cache file names are key digests, so no name-based guess is accepted.
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from io import BytesIO
from pathlib import Path

import pytest
from PIL import Image, ImageDraw

from memripal.backend import MetaBackend
from memripal.imaging import process_upload
from memripal.loci import find_loci
from memripal.meta_client import CallResult

REPO_ROOT = Path(__file__).resolve().parents[1]
ROOM_ID = "dim-kitchen"
# Built by concatenation so this file never matches the pre-commit secret scanner (MEM-004).
FAKE_KEY = "fake" + "-promote-" + "p" * 24
PHRASES = ["kettle", "toaster", "spice rack", "cutting board"]
DATE = r"\d{4}-\d{2}-\d{2}"
MANIFEST_HEAD = "# Fixtures manifest\n\n| Path | Source | License |\n| --- | --- | --- |\n"
EXISTING_ROW = (
    "| `demo/photo.jpg` | synthetic, generated by scripts/make_synthetic_fixtures.py | MIT (own work) |"
)


def _image(fmt: str, color: tuple[int, int, int], size=(640, 480)) -> bytes:
    img = Image.new("RGB", size, color)
    draw = ImageDraw.Draw(img)
    for i in range(4):
        draw.rectangle((40 + 140 * i, 120, 140 + 140 * i, 360), fill=(200 - 40 * i, 60 + 30 * i, 90))
    buf = BytesIO()
    img.save(buf, format=fmt)
    return buf.getvalue()


def _ok(body: bytes) -> CallResult:
    return CallResult(ok=True, status=200, body=body, error=None, attempts=1, latency_s=0.01)


class FakeClient:
    """MetaBackend's client: Spark phrases and one SAM box per phrase, no network."""

    def chat_json(self, **kwargs):
        content = '{"phrases": [' + ", ".join(f'"{p}"' for p in PHRASES) + "]}"
        body = '{"choices": [{"message": {"content": ' + json.dumps(content) + "}}]}"
        return _ok(body.encode("utf-8"))

    def segment(self, **kwargs):
        text = f"<ref>{kwargs['phrase']}</ref><box>(40,120),(140,360)</box>"
        return _ok(('{"output_text": ' + json.dumps(text) + "}").encode("utf-8"))


def _entries(cache: Path) -> dict[str, bytes]:
    """Response entries (method/<digest><ext>) in the live cache; photos/ is not an entry."""
    return {
        p.relative_to(cache).as_posix(): p.read_bytes()
        for p in sorted(cache.rglob("*"))
        if p.is_file() and p.relative_to(cache).parts[0] != "photos"
    }


def _seed(cache: Path, photo: bytes) -> dict[str, bytes]:
    """Record one live find_loci run for `photo` through the real MetaBackend; return the new entries."""
    before = _entries(cache)
    backend = MetaBackend(FAKE_KEY, cache_root=cache, client=FakeClient())
    find_loci(backend, process_upload(photo), clock=lambda: 0.0)
    return {k: v for k, v in _entries(cache).items() if k not in before}


class Sandbox:
    def __init__(self, root: Path):
        self.root = root
        self.fixtures = root / "fixtures"
        self.replay = self.fixtures / "replay"
        self.cache = root / "refs" / "private" / "live-cache"
        self.manifest = self.fixtures / "MANIFEST.md"
        self.room_entries: dict[str, bytes] = {}
        self.other_entries: dict[str, bytes] = {}


@pytest.fixture
def box(tmp_path) -> Sandbox:
    """Temp root: scripts/*.py, fixtures/rooms/<ROOM_ID>.webp, fixtures/MANIFEST.md, a seeded live cache."""
    sb = Sandbox(tmp_path / "root")
    (sb.root / "scripts").mkdir(parents=True)
    for script in (REPO_ROOT / "scripts").glob("*.py"):
        shutil.copy2(script, sb.root / "scripts")
    room = _image("WEBP", (50, 45, 40))
    (sb.fixtures / "rooms").mkdir(parents=True)
    (sb.fixtures / "rooms" / f"{ROOM_ID}.webp").write_bytes(room)
    sb.manifest.write_text(MANIFEST_HEAD + EXISTING_ROW + "\n", encoding="utf-8", newline="\n")
    sb.room_entries = _seed(sb.cache, room)
    sb.other_entries = _seed(sb.cache, _image("JPEG", (180, 170, 150)))
    assert sb.room_entries and sb.other_entries
    assert not set(sb.room_entries) & set(sb.other_entries)
    assert (sb.cache / "photos").is_dir()
    return sb


def _env() -> dict[str, str]:
    env = {k: v for k, v in os.environ.items() if k != "META_API_KEY"}
    src = str(REPO_ROOT / "src")
    env["PYTHONPATH"] = src + (os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
    return env


def _promote(sb: Sandbox, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(sb.root / "scripts" / "promote_live_cache.py"), *args],
        cwd=str(sb.root),
        env=_env(),
        capture_output=True,
        text=True,
        timeout=120,
    )


def _tree(root: Path) -> dict[str, tuple[bytes, int]]:
    if not root.exists():
        return {}
    return {
        p.relative_to(root).as_posix(): (p.read_bytes(), p.stat().st_mtime_ns)
        for p in sorted(root.rglob("*"))
        if p.is_file()
    }


def _replay_files(sb: Sandbox) -> dict[str, bytes]:
    return {k: v for k, (v, _) in _tree(sb.replay).items()}


def _rows(text: str, rel: str) -> list[list[str]]:
    return [
        [cell.strip() for cell in line.strip().strip("|").split("|")]
        for line in text.splitlines()
        if f"`replay/{rel}`" in line
    ]


# Covers: MEM-043
class TestPromoteCopiesOnlyTheRoom:
    def test_copies_exactly_the_rooms_entries_none_from_photos_or_other_photo(self, box):
        result = _promote(box, "--room", ROOM_ID)
        assert result.returncode == 0, result.stderr
        assert _replay_files(box) == box.room_entries
        assert not (box.replay / "photos").exists()
        assert not set(_replay_files(box)) & set(box.other_entries)

    def test_live_cache_is_left_untouched(self, box):
        before = _tree(box.cache)
        result = _promote(box, "--room", ROOM_ID)
        assert result.returncode == 0, result.stderr
        assert _tree(box.cache) == before

    def test_copied_files_pass_precommit_scan(self, box):
        result = _promote(box, "--room", ROOM_ID)
        assert result.returncode == 0, result.stderr
        copied = [str(box.replay / rel) for rel in box.room_entries]
        scan = subprocess.run(
            [sys.executable, str(REPO_ROOT / "scripts" / "precommit_scan.py"), *copied],
            capture_output=True,
            text=True,
            timeout=60,
        )
        assert scan.returncode == 0, scan.stderr

    def test_room_photo_sha_keys_every_copied_entry_through_the_backend(self, box):
        room = (box.fixtures / "rooms" / f"{ROOM_ID}.webp").read_bytes()
        sha = hashlib.sha256(process_upload(room).jpeg).hexdigest()
        result = _promote(box, "--room", ROOM_ID)
        assert result.returncode == 0, result.stderr
        assert (box.cache / "photos" / f"{sha}.jpg").is_file()
        assert set(_replay_files(box)) == set(box.room_entries)


# Covers: MEM-043
class TestPromoteManifestRows:
    def test_one_adr_0029_row_per_copied_file_and_existing_rows_kept(self, box):
        result = _promote(box, "--room", ROOM_ID)
        assert result.returncode == 0, result.stderr
        text = box.manifest.read_text(encoding="utf-8")
        assert EXISTING_ROW in text.splitlines()
        source = (
            rf"live Meta responses for room {re.escape(ROOM_ID)}, "
            rf"promoted by scripts/promote_live_cache\.py, {DATE}"
        )
        for rel in box.room_entries:
            rows = _rows(text, rel)
            assert len(rows) == 1, (rel, rows)
            assert re.fullmatch(source, rows[0][1]), rows[0][1]
            assert "ADR 0029" in rows[0][2]
        for rel in box.other_entries:
            assert _rows(text, rel) == []


# Covers: MEM-043
class TestPromoteIdempotentAndSafe:
    def test_rerun_changes_no_file_bytes_or_mtimes(self, box):
        first = _promote(box, "--room", ROOM_ID)
        assert first.returncode == 0, first.stderr
        before = _tree(box.fixtures)
        second = _promote(box, "--room", ROOM_ID)
        assert second.returncode == 0, second.stderr
        assert _tree(box.fixtures) == before

    def test_equal_bytes_target_is_skipped_and_the_rest_copied(self, box):
        rel = sorted(box.room_entries)[0]
        target = box.replay / rel
        target.parent.mkdir(parents=True)
        target.write_bytes(box.room_entries[rel])
        mtime = target.stat().st_mtime_ns
        result = _promote(box, "--room", ROOM_ID)
        assert result.returncode == 0, result.stderr
        assert target.stat().st_mtime_ns == mtime
        assert _replay_files(box) == box.room_entries

    def test_conflicting_target_exits_1_and_writes_nothing(self, box):
        rel = sorted(box.room_entries)[-1]
        target = box.replay / rel
        target.parent.mkdir(parents=True)
        target.write_bytes(b"different bytes already committed")
        before = _tree(box.fixtures)
        result = _promote(box, "--room", ROOM_ID)
        assert result.returncode == 1
        assert result.stderr.strip()
        assert _tree(box.fixtures) == before

    def test_dry_run_prints_target_paths_and_writes_nothing(self, box):
        before = _tree(box.fixtures)
        result = _promote(box, "--room", ROOM_ID, "--dry-run")
        assert result.returncode == 0, result.stderr
        stdout = result.stdout.replace("\\", "/")
        for rel in box.room_entries:
            assert f"replay/{rel}" in stdout, rel
        for rel in box.other_entries:
            assert rel not in stdout
        assert _tree(box.fixtures) == before

    @pytest.mark.parametrize("room_id", ["no-such-room", "../rooms", "Bad_ID"])
    def test_unknown_or_invalid_room_writes_nothing(self, box, room_id):
        before = _tree(box.fixtures)
        result = _promote(box, "--room", room_id)
        assert result.returncode != 0
        assert _tree(box.fixtures) == before
