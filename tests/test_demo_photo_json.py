# Covers: MEM-087
"""Contract (MEM-087, ADR 0048 Decision): static/assets/demo_photo.json is the sentinel JPEG the
Memorize client sends for photo-less demo stations. It must be byte-exact fixtures/demo/photo.jpg, since
the photo keys the /split replay fixture, and it is regenerated by a script, never by hand.

- static/assets/demo_photo.json is one JSON string: base64 of fixtures/demo/photo.jpg.
- scripts/gen_demo_photo_json.py [--in PATH] [--out PATH]; --in defaults to fixtures/demo/photo.jpg and
  --out to static/assets/demo_photo.json, both resolved from the repo root (the script's parent's
  parent), not the cwd. It writes json.dumps(base64(input)) + "\\n", byte-equal to the committed file,
  and exits 0.
- A missing --in file -> non-zero exit, stderr names the missing path, no traceback, --out not written.
"""

import base64
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = REPO_ROOT / "scripts" / "gen_demo_photo_json.py"
PHOTO = REPO_ROOT / "fixtures" / "demo" / "photo.jpg"
PHOTO_JSON = REPO_ROOT / "static" / "assets" / "demo_photo.json"
TIMEOUT_S = 60


def _run(script: Path, *args: str, cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(script), *args],
        cwd=str(cwd),
        check=False,
        capture_output=True,
        text=True,
        timeout=TIMEOUT_S,
    )


# Requirement: the committed sentinel JSON decodes to exactly the demo photo's bytes, so a photo-less
# /split sends the same photo the replay fixture was recorded with.
class TestCommittedDemoPhotoJson:
    def test_is_one_json_string(self):
        assert isinstance(json.loads(PHOTO_JSON.read_bytes()), str)

    def test_decodes_to_demo_photo_bytes(self):
        encoded = json.loads(PHOTO_JSON.read_bytes())
        assert base64.b64decode(encoded, validate=True) == PHOTO.read_bytes()


# Requirement: scripts/gen_demo_photo_json.py regenerates the sentinel JSON from the demo photo,
# byte-equal to the committed file; --in/--out override the repo-root defaults; a missing input fails
# loudly with a clear message and writes nothing.
class TestGenDemoPhotoJson:
    def test_default_input_regenerates_the_committed_json_byte_for_byte(self, tmp_path):
        out = tmp_path / "demo_photo.json"
        result = _run(SCRIPT, "--out", str(out), cwd=tmp_path)
        assert result.returncode == 0, result.stderr
        assert out.read_bytes() == PHOTO_JSON.read_bytes()

    def test_both_defaults_resolve_from_the_repo_root_not_the_cwd(self, tmp_path):
        fake_repo = tmp_path / "repo"
        (fake_repo / "scripts").mkdir(parents=True)
        (fake_repo / "fixtures" / "demo").mkdir(parents=True)
        (fake_repo / "static" / "assets").mkdir(parents=True)
        shutil.copyfile(SCRIPT, fake_repo / "scripts" / SCRIPT.name)
        shutil.copyfile(PHOTO, fake_repo / "fixtures" / "demo" / "photo.jpg")
        elsewhere = tmp_path / "elsewhere"
        elsewhere.mkdir()
        result = _run(fake_repo / "scripts" / SCRIPT.name, cwd=elsewhere)
        assert result.returncode == 0, result.stderr
        assert (fake_repo / "static" / "assets" / "demo_photo.json").read_bytes() == PHOTO_JSON.read_bytes()

    def test_custom_input_round_trips(self, tmp_path):
        src = tmp_path / "other.jpg"
        src.write_bytes(b"\xff\xd8\xff\xe0not-really-a-photo\x00\x01\xff\xd9")
        out = tmp_path / "out.json"
        result = _run(SCRIPT, "--in", str(src), "--out", str(out), cwd=tmp_path)
        assert result.returncode == 0, result.stderr
        raw = out.read_bytes()
        assert raw.endswith(b'"\n')
        assert base64.b64decode(json.loads(raw), validate=True) == src.read_bytes()

    def test_missing_input_exits_non_zero_with_a_clear_message(self, tmp_path):
        missing = tmp_path / "no_such_photo.jpg"
        out = tmp_path / "out.json"
        result = _run(SCRIPT, "--in", str(missing), "--out", str(out), cwd=tmp_path)
        assert result.returncode != 0
        assert "no_such_photo.jpg" in result.stderr
        assert "Traceback" not in result.stderr
        assert not out.exists()
