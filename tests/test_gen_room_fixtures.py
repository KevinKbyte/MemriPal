class TestDryRun:
    def test_dry_run_offline_prints_one_line_per_room_and_call_count(self, monkeypatch, out, capsys):
        mod = _load()
        monkeypatch.delenv("META_API_KEY", raising=False)
        before = _tree(out.parent)
        code = mod.main(["--dry-run", "--out", str(out)], make_client=_refuse_factory)
        lines = [line for line in capsys.readouterr().out.splitlines() if line.strip()]
        assert code == 0
        assert lines[-1].strip() == f"calls: {len(mod.ROOMS)}"
        assert len(lines) == len(mod.ROOMS) + 1
        for line, (room_id, _) in zip(lines, mod.ROOMS, strict=False):
            assert room_id in line
            assert str(out / f"{room_id}.webp") in line
            assert "skip" not in line
        assert _tree(out.parent) == before

    def test_dry_run_marks_present_room_skip_and_counts_only_missing(self, monkeypatch, out, capsys):
        mod = _load()
        monkeypatch.setenv("META_API_KEY", KEY)
        present_id = mod.ROOMS[0][0]
        out.mkdir()
        (out / f"{present_id}.webp").write_bytes(ROOM_IMAGES[0])
        before = _tree(out.parent)
        code = mod.main(["--dry-run", "--out", str(out)], make_client=_refuse_factory)
        captured = capsys.readouterr()
        lines = [line for line in captured.out.splitlines() if line.strip()]
        assert code == 0
        assert lines[-1].strip() == f"calls: {len(mod.ROOMS) - 1}"
        assert "skip" in lines[0] and present_id in lines[0]
        assert all("skip" not in line for line in lines[1:-1])
        assert KEY not in captured.out + captured.err
        assert _tree(out.parent) == before

    def test_dry_run_default_out_is_fixtures_rooms(self, monkeypatch, capsys):
        mod = _load()
        monkeypatch.delenv("META_API_KEY", raising=False)
        code = mod.main(["--dry-run"], make_client=_refuse_factory)
        stdout = capsys.readouterr().out.replace("\\", "/")
        assert code == 0
        for room_id, _ in mod.ROOMS:
            assert f"fixtures/rooms/{room_id}.webp" in stdout


