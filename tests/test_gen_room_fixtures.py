        mod = _load()
        _run(monkeypatch, mod, out, _all_ok(mod))
        _run(monkeypatch, mod, out, [])
        text = _manifest(out)
        for room_id, _ in mod.ROOMS:
            assert len(_room_rows(text, room_id)) == 1


