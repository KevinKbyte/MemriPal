# Covers: MEM-043
# Requirement (G2, G3, V1): scripts/gen_room_fixtures.py makes 3-5 hard test rooms with Kev's own key:
# one image_generate call per missing room (ROOMS order, never retried), prompt = room subject + the
# shared REALISM suffix (casual smartphone snapshot: tilt, wide-angle, mixed light, blown windows,
# grain, clutter), output <out>/<room_id>.webp = returned bytes unchanged (default out fixtures/rooms).
# An existing room file is skipped with no call, so committed bytes are never regenerated. --dry-run
# prints one line per room ("skip" when present) then "calls: <missing>", with no key, client or
# write. Unset/blank META_API_KEY exits 2 before any call or write. An undecodable or EXIF-bearing
# body, or a failed call, fails that room ("<room_id>: failed (<error or bad_image>)"), writes
# nothing for it, the next room runs, exit 1. make_variants(base) derives 6 deterministic intake
# variants offline whose imaging.process_upload outcomes are pinned per V1.
#
# Decision (Q23 default): the generator writes each new room's fixtures/MANIFEST.md row (the manifest
# is <out>/../MANIFEST.md, the row path is relative to it, e.g. `rooms/<room_id>.webp`), keeping every
# existing row; a skipped or failed room gets no new row.
