def _size(data: bytes) -> tuple[int, int]:
    with Image.open(BytesIO(data)) as img:
        return img.size


# Covers: MEM-043
class TestVariants:
    def test_exactly_six_named_variants_of_bytes(self, base):
        variants = _variants(base)
        assert set(variants) == VARIANT_KEYS
        assert all(isinstance(v, bytes) and v for v in variants.values())

    def test_second_call_is_byte_identical(self, base):
        mod = _load()
        variants = _variants(base)
        assert mod.make_variants(base) == variants

    def test_orientation_rotated_pixels_restored_by_exif_tag(self, base):
        variants = _variants(base)
        data = variants["orientation"]
        bw, bh = _size(base)
        with Image.open(BytesIO(data)) as img:
            assert img.size == (bh, bw)
            assert img.getexif().get(0x0112) in (6, 8)
        processed, expected = process_upload(data), process_upload(base)
        assert (processed.width, processed.height) == (expected.width, expected.height)

    def test_gps_is_accepted_and_exif_is_stripped(self, base):
        variants = _variants(base)
        data = variants["gps"]
        with Image.open(BytesIO(data)) as img:
            assert img.getexif().get_ifd(0x8825)
        processed = process_upload(data)
        assert b"Exif\x00\x00" not in processed.jpeg
        with Image.open(BytesIO(processed.jpeg)) as img:
            assert len(img.getexif()) == 0

    def test_heic_is_iso_bmff_ftyp_and_rejected_bad_magic(self, base):
        variants = _variants(base)
        data = variants["heic"]
        assert data[4:8] == b"ftyp"
        assert data[8:12] == b"heic"
        with pytest.raises(ImageRejected) as exc:
            process_upload(data)
        assert str(exc.value) == "bad_magic"
        assert exc.value.status == 400

    def test_no_pillow_heif_dependency(self):
        assert "pillow-heif" not in (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8").lower()

    def test_oversize_long_side_6000_within_caps_processed_to_2048(self, base):
        variants = _variants(base)
        data = variants["oversize"]
        w, h = _size(data)
        assert max(w, h) == 6000
        assert max(w, h) <= imaging.MAX_SIDE
        assert w * h <= imaging.MAX_PIXELS
        assert len(data) <= imaging.MAX_UPLOAD_BYTES
        processed = process_upload(data)
        assert max(processed.width, processed.height) == imaging.LONG_SIDE == 2048

    def test_heavy_jpeg_is_a_smaller_jpeg_and_accepted(self, base):
        variants = _variants(base)
        data = variants["heavy-jpeg"]
        assert imaging.sniff(data) == "jpeg"
        assert _size(data) == _size(base)
        assert len(data) < len(base)
        assert process_upload(data).sha

    def test_aspect_is_9_16_portrait_and_processed_within_1_percent(self, base):
        variants = _variants(base)
        data = variants["aspect"]
        w, h = _size(data)
        assert w < h
        processed = process_upload(data)
        assert abs(processed.width / processed.height - 9 / 16) <= 0.01 * (9 / 16)
