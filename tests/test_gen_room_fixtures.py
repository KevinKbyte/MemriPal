class TestRoomFailure:
    @pytest.mark.parametrize(
        ("result", "reason"),
        [
            (_fail(500, "500 http_error"), "500 http_error"),
            (_fail(None, "transport: ConnectError"), "transport: ConnectError"),
            (_ok_raw(_body(b"definitely not an image")), "bad_image"),
            (_ok_raw(b"not json at all"), "bad_image"),
            (_ok(_exif_webp()), "bad_image"),
        ],
        ids=["5xx", "transport", "undecodable", "non_json", "exif"],
    )
    def test_failed_first_room_writes_nothing_next_rooms_run_exit_1(
        self, monkeypatch, out, capsys, result, reason
    ):
        mod = _load()
        rest = [_ok(ROOM_IMAGES[i]) for i in range(1, len(mod.ROOMS))]
        code, factory = _run(monkeypatch, mod, out, [result, *rest])
        captured = capsys.readouterr()
        first_id = mod.ROOMS[0][0]
        assert code == 1
        assert f"{first_id}: failed ({reason})" in captured.err
        assert not (out / f"{first_id}.webp").exists()
        assert _room_rows(_manifest(out), first_id) == []
        assert len(factory.client.calls) == len(mod.ROOMS)
        for i, (room_id, _) in enumerate(mod.ROOMS[1:], start=1):
            assert (out / f"{room_id}.webp").read_bytes() == ROOM_IMAGES[i]
            assert len(_room_rows(_manifest(out), room_id)) == 1


