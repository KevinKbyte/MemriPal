REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = REPO_ROOT / "scripts" / "gen_room_fixtures.py"
DEMO_PHOTO = REPO_ROOT / "fixtures" / "demo" / "photo.jpg"

# Built by concatenation so this file never matches the pre-commit secret scanner (MEM-004).
KEY = "fake" + "-gen-rooms-" + "r" * 24
MISSING_KEY_MSG = "META_API_KEY is not set; launch via scripts/run_live.ps1"
ROOM_ID = re.compile(r"^[a-z0-9-]{1,32}$")
DATE = r"\d{4}-\d{2}-\d{2}"
VARIANT_KEYS = {"orientation", "gps", "heic", "oversize", "heavy-jpeg", "aspect"}
MANIFEST_HEAD = "# Fixtures manifest\n\n| Path | Source | License |\n| --- | --- | --- |\n"
EXISTING_ROW = (
    "| `demo/photo.jpg` | synthetic, generated by scripts/make_synthetic_fixtures.py | MIT (own work) |"
)


def _load():
    spec = importlib.util.spec_from_file_location("gen_room_fixtures_under_test", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _webp(color: tuple[int, int, int], *, exif: bytes | None = None) -> bytes:
    buf = BytesIO()
    kwargs = {"exif": exif} if exif is not None else {}
    Image.new("RGB", (64, 48), color).save(buf, format="WEBP", **kwargs)
    return buf.getvalue()


ROOM_IMAGES = [_webp((40 * i, 200 - 30 * i, 90)) for i in range(5)]


def _exif_webp() -> bytes:
    exif = Image.Exif()
    exif[0x010F] = "FakeCam"
    return _webp((10, 10, 10), exif=exif.tobytes())


def _body(image: bytes) -> bytes:
    return json.dumps({"data": [{"b64_json": base64.b64encode(image).decode("ascii")}]}).encode()


def _ok(image: bytes) -> CallResult:
    return CallResult(ok=True, status=200, body=_body(image), error=None, attempts=1, latency_s=0.01)


def _ok_raw(body: bytes) -> CallResult:
    return CallResult(ok=True, status=200, body=body, error=None, attempts=1, latency_s=0.01)


def _fail(status: int | None, error: str) -> CallResult:
    return CallResult(ok=False, status=status, body=b"", error=error, attempts=1, latency_s=0.01)


class FakeClient:
    """Only image_generate exists: any other MetaClient method (image_edit, chat_json, ...) raises."""

    def __init__(self, results: list[CallResult]):
        self._results = list(results)
        self.calls: list[dict] = []

    def image_generate(self, *, prompt, model="muse-image-1.0", output_format="webp", timeout=None):
        self.calls.append({"prompt": prompt, "model": model, "output_format": output_format})
        if not self._results:
            raise AssertionError("more image_generate calls than canned results")
        return self._results.pop(0)


class FakeFactory:
    """Stands in for make_client=MetaClient; records the arguments it was built with."""

    def __init__(self, results: list[CallResult]):
        self.client = FakeClient(results)
        self.built: list[tuple[tuple, dict]] = []

    def __call__(self, *args, **kwargs) -> FakeClient:
        self.built.append((args, kwargs))
        return self.client


def _refuse_factory(*args, **kwargs):
    raise AssertionError("client built when none was expected")


def _no_network(*args, **kwargs):
    raise AssertionError("network access attempted")


@pytest.fixture(autouse=True)
def _offline(monkeypatch):
    monkeypatch.setattr(socket, "getaddrinfo", _no_network)
    monkeypatch.setattr(socket, "create_connection", _no_network)


@pytest.fixture
def out(tmp_path) -> Path:
    """<tmp>/fixtures/rooms with a seeded <tmp>/fixtures/MANIFEST.md holding one existing row."""
    fixtures = tmp_path / "fixtures"
    fixtures.mkdir()
    (fixtures / "MANIFEST.md").write_text(MANIFEST_HEAD + EXISTING_ROW + "\n", encoding="utf-8", newline="\n")
    return fixtures / "rooms"


def _tree(root: Path) -> dict[str, bytes]:
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


def _manifest(out: Path) -> str:
    return (out.parent / "MANIFEST.md").read_text(encoding="utf-8")


def _room_rows(text: str, room_id: str) -> list[str]:
    return [line for line in text.splitlines() if f"`rooms/{room_id}.webp`" in line]


def _all_ok(mod) -> list[CallResult]:
    return [_ok(ROOM_IMAGES[i]) for i in range(len(mod.ROOMS))]


def _run(monkeypatch, mod, out: Path, results, *, extra=()):
    monkeypatch.setenv("META_API_KEY", KEY)
    factory = FakeFactory(results)
    code = mod.main(["--out", str(out), *extra], make_client=factory)
    return code, factory


