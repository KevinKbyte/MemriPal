class TestRoomsAndPrompts:
    def test_rooms_is_a_fixed_tuple_of_3_to_5_unique_valid_ids(self):
        mod = _load()
        assert isinstance(mod.ROOMS, tuple)
        assert 3 <= len(mod.ROOMS) <= 5
        ids = [room_id for room_id, _ in mod.ROOMS]
        assert all(ROOM_ID.fullmatch(room_id) for room_id in ids), ids
        assert len(set(ids)) == len(ids)
        assert all(isinstance(subject, str) and subject.strip() for _, subject in mod.ROOMS)

    def test_realism_suffix_asks_for_a_casual_smartphone_snapshot(self):
        mod = _load()
        realism = mod.REALISM.lower()
        for word in ("smartphone", "tilt", "wide-angle", "window", "grain", "clutter"):
            assert word in realism, word

    @pytest.mark.parametrize("trait", ["clutter", "dim", "tilt"])
    def test_at_least_one_room_subject_is_cluttered_dim_and_tilted(self, trait):
        mod = _load()
        assert any(trait in subject.lower() for _, subject in mod.ROOMS), trait

    def test_every_prompt_is_subject_plus_realism_in_rooms_order(self, monkeypatch, out):
        mod = _load()
        code, factory = _run(monkeypatch, mod, out, _all_ok(mod))
        assert code == 0
        prompts = [call["prompt"] for call in factory.client.calls]
        assert len(prompts) == len(mod.ROOMS)
        for prompt, (_, subject) in zip(prompts, mod.ROOMS, strict=True):
            assert prompt.startswith(subject)
            assert prompt.endswith(mod.REALISM)
            assert prompt[len(subject) : len(prompt) - len(mod.REALISM)].strip(" ,.;") == ""


