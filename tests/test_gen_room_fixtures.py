class TestManifestRow:
    def test_each_new_room_gets_one_adr_0029_row_and_existing_rows_kept(self, monkeypatch, out):
        mod = _load()
        code, _ = _run(monkeypatch, mod, out, _all_ok(mod))
        text = _manifest(out)
        assert code == 0
        assert EXISTING_ROW in text.splitlines()
